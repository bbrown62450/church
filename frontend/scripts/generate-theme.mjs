// The app's Material 3 colors (Theme PR 1). Generates the color tokens in
// src/app/globals.css from one seed with Google's Material Color Utilities
// (the "tonal spot" scheme, standard contrast), so the page needs no color
// library at run time. Run `node scripts/generate-theme.mjs --write` after
// changing the seed or the role map; src/lib/theme/tokens.test.ts fails while
// the committed block differs from what this prints.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import {
  Blend,
  Hct,
  MaterialDynamicColors as M,
  SchemeTonalSpot,
  TonalPalette,
  argbFromHex,
  hexFromArgb,
} from "@material/material-color-utilities";

/** The owner's chosen preview (Option B, teal). */
export const SEED = "#006A60";
/** The warning text color's source, harmonized toward the seed (Material's "custom color" recipe). */
export const WARNING_SOURCE = "#B45309";

/** shadcn's variable → the Material 3 role it takes, in both modes. */
const ROLES = {
  background: "surface",
  foreground: "onSurface",
  card: "surfaceContainerLow",
  "card-foreground": "onSurface",
  popover: "surfaceContainer",
  "popover-foreground": "onSurface",
  primary: "primary",
  "primary-foreground": "onPrimary",
  "primary-container": "primaryContainer",
  "primary-container-foreground": "onPrimaryContainer",
  secondary: "secondaryContainer",
  "secondary-foreground": "onSecondaryContainer",
  muted: "surfaceContainerHigh",
  "muted-foreground": "onSurfaceVariant",
  accent: "surfaceContainerHighest",
  "accent-foreground": "onSurface",
  destructive: "error",
  border: "outlineVariant",
  input: "outline",
  ring: "primary",
  "surface-container": "surfaceContainer",
  "chart-1": "primary",
  "chart-2": "secondary",
  "chart-3": "tertiary",
  "chart-4": "primaryContainer",
  "chart-5": "tertiaryContainer",
  sidebar: "surfaceContainerLow",
  "sidebar-foreground": "onSurface",
  "sidebar-primary": "primary",
  "sidebar-primary-foreground": "onPrimary",
  "sidebar-accent": "secondaryContainer",
  "sidebar-accent-foreground": "onSecondaryContainer",
  "sidebar-border": "outlineVariant",
  "sidebar-ring": "primary",
};

/**
 * Every token for one mode, as `#rrggbb`.
 * @param {boolean} dark
 * @returns {Record<string, string>}
 */
export function themeTokens(dark) {
  const scheme = new SchemeTonalSpot(Hct.fromInt(argbFromHex(SEED)), dark, 0);
  /** @type {Record<string, string>} */
  const tokens = {};
  for (const [name, role] of Object.entries(ROLES)) tokens[name] = hexFromArgb(M[role].getArgb(scheme));
  const warning = TonalPalette.fromInt(Blend.harmonize(argbFromHex(WARNING_SOURCE), argbFromHex(SEED)));
  tokens.warning = hexFromArgb(warning.tone(dark ? 80 : 40));
  return tokens;
}

const block = (selector, tokens, indent = "") =>
  [`${indent}${selector} {`, ...Object.entries(tokens).map(([k, v]) => `${indent}  --${k}: ${v};`), `${indent}}`].join("\n");

export const START = "/* theme:start (generated by scripts/generate-theme.mjs; edit the script, not these lines) */";
export const END = "/* theme:end */";

/** The generated part of globals.css: light on :root, dark under the phone's setting, and `.paper` always light. */
export function themeCss() {
  const light = themeTokens(false);
  const dark = themeTokens(true);
  return [
    START,
    block(":root", light),
    "",
    "@media (prefers-color-scheme: dark) {",
    block(":root", dark, "  "),
    "}",
    "",
    "/* Anything that stands for paper (the printed bulletin) stays light in dark mode. */",
    block(".paper", light),
    END,
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const css = themeCss();
  if (process.argv.includes("--write")) {
    const path = fileURLToPath(new URL("../src/app/globals.css", import.meta.url));
    const text = readFileSync(path, "utf8");
    const from = text.indexOf("/* theme:start");
    const to = text.indexOf(END);
    if (from < 0 || to < from) throw new Error("globals.css has no theme:start/theme:end block");
    writeFileSync(path, text.slice(0, from) + css + text.slice(to + END.length));
    console.log("globals.css: theme block written");
  } else {
    console.log(css);
  }
}
